"""RiskReport: the final, consolidated output of the Risk/Report Agent.

Combines every specialist agent's report (zoning, litigation, document
analysis, and any future ones) with an overall score from RiskScorer and
the mandatory disclaimer (CLAUDE.md hard guardrail #3). This is the one
artifact meant to actually reach a buyer -- specialist reports stay
internal/intermediate, so only this schema carries the disclaimer.
"""

from datetime import datetime
from typing import Annotated, Self, Union

from pydantic import BaseModel, Field, computed_field, model_validator

from bhoomicheck.schemas.document import DocumentAnalysisReport
from bhoomicheck.schemas.finding import Finding
from bhoomicheck.schemas.growth_potential import GrowthPotentialReport
from bhoomicheck.schemas.land_records import LandRecordsReport
from bhoomicheck.schemas.litigation import LitigationReport
from bhoomicheck.schemas.owner_background import OwnerBackgroundReport
from bhoomicheck.schemas.parcel import ParcelIdentifier
from bhoomicheck.schemas.prohibited import ProhibitedPropertyReport
from bhoomicheck.schemas.scoring import ScoredFinding
from bhoomicheck.schemas.zoning import ZoningReport

# A discriminated union, not list[BaseAgentReport], and the difference is
# a bug rather than a style preference.
#
# Pydantic validates and serializes by the *annotated* type. Annotated as
# the base class, a ZoningReport round-tripping through a checkpoint came
# back as a BaseAgentReport with every subclass field silently dropped --
# its road_assessment and its extracts gone, no error raised. In-memory
# runs never showed it because nothing was ever deserialized; the HTTP
# API, which checkpoints to SQLite, lost the measured road table on every
# report.
#
# Each specialist report already pins `agent_name` to a distinct Literal,
# so that field is a ready-made discriminator: Pydantic can tell which
# concrete class a serialized report belongs to and rebuild it intact.
# The set of specialist agents is closed and small, so enumerating them
# costs little and makes a missing one a loud validation error rather
# than a quiet truncation (architecture principle 6).
SpecialistReport = Annotated[
    Union[
        DocumentAnalysisReport,
        ZoningReport,
        LitigationReport,
        LandRecordsReport,
        OwnerBackgroundReport,
        GrowthPotentialReport,
        ProhibitedPropertyReport,
    ],
    Field(discriminator="agent_name"),
]

DISCLAIMER = (
    "This report is generated by an automated due-diligence tool based on "
    "publicly available records, which may be incomplete, outdated, or "
    "contain errors. It does not constitute legal advice, and does not "
    "guarantee clear title or freedom from encumbrances. Consult a "
    "licensed advocate before making any purchase decision based on this "
    "report."
)


class RiskReport(BaseModel):
    """The final report a buyer actually reads.

    Attributes:
        parcel: The parcel this report is about.
        generated_at: When this consolidated report was assembled.
        overall_score: 0-100 from RiskScorer, 100 = no issues found across
            every specialist report.
        scored_findings: Every finding that fed the score, with which
            rule fired for each -- the audit trail behind overall_score.
        superseded_findings: Findings for a check another source
            answered better. Kept, not discarded: a reader is entitled to
            know a second source was consulted and what it said. These
            are NOT scored -- scoring one question twice was a real
            defect this field's existence records the fix for.
        conflicting_checks: check_ids where two sources both answered and
            answered differently. Not the ordinary case of one source
            being unable to answer -- a genuine disagreement, which is a
            reason to trust neither until a human looks.
        specialist_reports: Every specialist report this was built from.
            Typed as the shared base contract (architecture principle 1)
            so this schema needs no change when a new specialist agent
            (land records, owner background, growth potential) is added.
    """

    parcel: ParcelIdentifier
    generated_at: datetime
    overall_score: int = Field(ge=0, le=100)
    scored_findings: list[ScoredFinding]
    superseded_findings: list[Finding] = []
    conflicting_checks: list[str] = []
    specialist_reports: list[SpecialistReport] = Field(min_length=1)

    @computed_field  # type: ignore[prop-decorator]
    @property
    def disclaimer(self) -> str:
        """The mandatory disclaimer (CLAUDE.md hard guardrail #3).

        A computed field, not a regular one with a default: that makes it
        impossible to construct a RiskReport with different disclaimer
        text, even by accident, while still serializing into
        model_dump()/model_dump_json() output like any other field.
        """
        return DISCLAIMER

    @model_validator(mode="after")
    def require_matching_parcel(self) -> Self:
        # A final report silently mixing findings from two different
        # parcels would be a serious, hard-to-notice bug -- reject it here.
        mismatched = [
            r.agent_name for r in self.specialist_reports if r.parcel != self.parcel
        ]
        if mismatched:
            raise ValueError(
                f"specialist report(s) {mismatched} have a different "
                "parcel than this RiskReport's parcel"
            )
        return self
